# --- /health ------------------------------------------------------------------------------


@pytest.fixture
def stores(monkeypatch: pytest.MonkeyPatch) -> dict[str, object]:
    """Live checks, replaced; a test changes the values before calling /health."""
    values: dict[str, object] = {"db": True, "chunks": 1750}
    monkeypatch.setattr(health_route, "database_ok", lambda: values["db"])
    monkeypatch.setattr(health_route, "chunk_count", lambda: values["chunks"])
    return values


def test_health_ready_is_200(stores, index: CorpusIndex) -> None:
    response = _client(_state(index)).get("/health")
    body = response.json()
    assert response.status_code == 200
    assert body["status"] == "ok"
    assert body["checks"] == {"database": "ok", "vector_store": "ok", "index": "ok"}
    assert body["documents"] == len(index.entries) and body["chunks"] == 1750
    assert len(body["planner_version"]) == 32


@pytest.mark.parametrize("chunks", [0, None])
def test_health_empty_or_missing_store_is_503_naming_it(stores, index: CorpusIndex, chunks) -> None:
    stores["chunks"] = chunks
    response = _client(_state(index)).get("/health")
    body = response.json()
    assert response.status_code == 503
    assert body["status"] == "not_ready"
    assert body["checks"]["vector_store"] == "unavailable"
    assert body["checks"]["database"] == "ok"                # the cause is named, unlike /query's 503


def test_health_catches_a_store_that_broke_after_startup(stores, index: CorpusIndex) -> None:
    """Readiness says ready (cached); the live database check says otherwise."""
    stores["db"] = False
    assert _client(_state(index)).get("/health").status_code == 503


def test_health_reports_readiness_failures_the_live_checks_miss(stores, index: CorpusIndex) -> None:
    """figure_guard has no live check of its own; readiness still counts it."""
    response = _client(_state(index, {"figure_guard": "FigureGuardError"})).get("/health")
    assert response.status_code == 503
    assert response.json()["checks"] == {"database": "ok", "vector_store": "ok", "index": "ok"}


def test_health_live_checks_never_create_a_store(monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
    """The real checks against empty paths: report unavailable, write nothing."""
    from src.utils.config import settings
    monkeypatch.setattr(settings, "SQLITE_DB_PATH", str(tmp_path / "db" / "metadata.db"))
    monkeypatch.setattr(settings, "CHROMA_DB_PATH", str(tmp_path / "db" / "chroma"))
    assert health_route.database_ok() is False
    assert health_route.chunk_count() is None
    assert not (tmp_path / "db").exists()
