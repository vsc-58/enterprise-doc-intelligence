def _record(doc_id: int, **values: object) -> ExtractedRecord:
    base: dict[str, object] = dict(
        document_id=doc_id, fiscal_year_end="2022-12-31", auditor_name="Auditor LLP",
        total_revenue=None, net_income=None, total_assets=None, total_liabilities=None,
        operating_cash_flow=None, extraction_strategy_used="S3", prompt_version="v1",
        model_name="gpt-4o-mini", extraction_status="success",
        extracted_at=datetime(2026, 9, 1, 12, 0, 0),
    )
    base.update(values)
    return ExtractedRecord(**base)


