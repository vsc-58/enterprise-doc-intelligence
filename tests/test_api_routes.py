@pytest.fixture(autouse=True)
def no_real_warm_up(monkeypatch: pytest.MonkeyPatch) -> None:
    """A re-try must never reach a real store in these tests."""
    async def no_warm(self: Readiness) -> None:
        return None
    monkeypatch.setattr(Readiness, "warm", no_warm)


def _state(index: CorpusIndex | None, failures: dict[str, str] | None = None) -> Readiness:
    state = Readiness()
    state.failures = dict(failures or {})
    state.index = index
    return state


def _client(state: Readiness) -> TestClient:
    app = create_app()
    app.dependency_overrides[get_readiness] = lambda: state
    return TestClient(app)


# --- /documents -------------------------------------------------------------------------


def test_documents_lists_the_corpus_by_ticker(index: CorpusIndex) -> None:
    body = _client(_state(index)).get("/documents").json()
    tickers = [d["ticker"] for d in body]
    assert tickers == sorted(tickers) and len(body) == len(index.entries)
    apple = next(d for d in body if d["ticker"] == "AAPL")
    assert apple == {"ticker": "AAPL", "company_name": "Apple Inc.", "cik": "0000320193",
                     "fiscal_year": 2021, "fiscal_year_end": "2021-09-25",
                     "is_extracted": True, "is_embedded": True}


def test_documents_uses_display_names(index: CorpusIndex) -> None:
    names = {d["ticker"]: d["company_name"] for d in _client(_state(index)).get("/documents").json()}
    assert names["BAC"] == "Bank of America Corp."          # not "BANK OF AMERICA CORP /DE/"
    assert names["MSFT"] == "Microsoft Corp."


def test_documents_works_without_the_vector_store(index: CorpusIndex) -> None:
    """Only the index is needed: a missing store must not hide the corpus list."""
    state = _state(index, {VECTOR_STORE: "EmptyVectorStore"})
    assert _client(state).get("/documents").status_code == 200


def test_documents_is_503_without_the_index() -> None:
    response = _client(_state(None, {"index": "RuntimeError"})).get("/documents")
    assert response.status_code == 503
    assert response.json()["error"] == "not_ready"


